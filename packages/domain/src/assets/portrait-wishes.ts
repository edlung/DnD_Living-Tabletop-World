import { entityIdSchema } from '@ltw/contracts';
import { z } from 'zod';

import { CorruptHistoryError } from '../kernel/corrupt-history.ts';
import { accept, reject, type Decision, type ResolvedCommandOf } from '../kernel/decision.ts';
import type { RecordedEvent, Restore } from '../kernel/events.ts';
import { withEntry, withoutEntry } from '../kernel/maps.ts';
import type { WorldState } from '../kernel/state.ts';

/**
 * A player's wish for a portrait of their own character (docs/adr/0056-characters-from-the-srd.md
 * §5): how they see it, kept until the DM asks for that character's picture — the DM's request
 * answers it, and undoing the request brings it back. Nothing is generated by the wish itself.
 */
const look = z.string().trim().min(1).max(300);

export const portraitAskedPayloadSchema = z.object({ characterId: entityIdSchema, look }).strict();

export const portraitWishRestoreSchemas = [
  z
    .object({
      fact: z.literal('portraitWish'),
      characterId: entityIdSchema,
      value: look.nullable(),
    })
    .strict(),
] as const;

export function decideAskPortrait(
  state: WorldState,
  command: ResolvedCommandOf<'AskPortrait'>,
): Decision {
  const entity = state.entities.get(command.characterId);
  if (entity?.kind !== 'character')
    return reject('ENTITY_NOT_FOUND', 'Only a character asks for its portrait');
  if (state.portraitWishes.get(command.characterId) === command.look)
    return reject('NO_EFFECT', 'That portrait is asked for already');
  return accept({
    type: 'PortraitAsked',
    payload: { characterId: command.characterId, look: command.look },
  });
}

export function applyPortraitAsked(
  state: WorldState,
  event: Extract<RecordedEvent, { type: 'PortraitAsked' }>,
): WorldState {
  const { characterId, look: wished } = event.payload;
  if (state.entities.get(characterId)?.kind !== 'character')
    throw new CorruptHistoryError(`portrait asked for ${characterId}, no character`);
  return { ...state, portraitWishes: withEntry(state.portraitWishes, characterId, wished) };
}

/** The DM's request for an entity's own picture answers a wish for it. */
export function withoutAnsweredWish(
  state: WorldState,
  event: Extract<RecordedEvent, { type: 'AssetRequested' }>,
): WorldState {
  const { entityId, variant } = event.payload;
  return variant === 'reference' && state.portraitWishes.has(entityId)
    ? { ...state, portraitWishes: withoutEntry(state.portraitWishes, entityId) }
    : state;
}

export function applyPortraitWishRestore(
  state: WorldState,
  restore: Extract<Restore, { fact: 'portraitWish' }>,
): WorldState {
  return {
    ...state,
    portraitWishes:
      restore.value === null
        ? withoutEntry(state.portraitWishes, restore.characterId)
        : withEntry(state.portraitWishes, restore.characterId, restore.value),
  };
}
