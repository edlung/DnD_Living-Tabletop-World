const fullParty = [...HERO_KEYS];

/** Every foe key a 4-player table can meet; the art manifest binds the crab figure to them. */
export const foeKeys: readonly string[] = PEARL_ENCOUNTERS.flatMap((e) =>
  foeRoster(e, fullParty.length).map((foe) => foe.key),
);
export const crabKeys: readonly string[] = PEARL_ENCOUNTERS.flatMap((e) =>
  foeRoster(e, fullParty.length)
    .filter((foe) => foe.srd !== 'animated-flying-sword')
    .map((foe) => foe.key),
);
export const pointerKeys: readonly string[] = PEARL_ENCOUNTERS.flatMap((e) =>
  foeRoster(e, fullParty.length)
    .filter((foe) => foe.srd === 'animated-flying-sword')
    .map((foe) => foe.key),
);

export const foeEntities = (party: readonly HeroKey[] = DEFAULT_PARTY): CampaignEntity[] =>
  PEARL_ENCOUNTERS.flatMap((e) => kitFoes(e, party.length));

export function encounters(party: readonly HeroKey[]): CampaignPackage['encounters'] {
  return PEARL_ENCOUNTERS.map((e) => kitEncounter(e, party));
}
