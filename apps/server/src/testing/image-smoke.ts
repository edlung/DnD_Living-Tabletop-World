import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { setTimeout as delay } from 'node:timers/promises';

import {
  DEFAULT_PERSONAS_FILE,
  DEV_DATABASE_URL,
  describeDatabaseUrl,
} from '../platform/config/config.ts';
import {
  SMOKE_USAGE,
  SmokeUsageError,
  parseSmokeArgs,
  type SmokeOptions,
} from './image-smoke/args.ts';
import { SmokeClient } from './image-smoke/client.ts';
import { EXIT, runImageSmoke } from './image-smoke/run.ts';
import { postgresSmokeStore } from './image-smoke/store.ts';

/**
 * `pnpm images:smoke --generator placeholder|openrouter-openai [--server http://127.0.0.1:3000]`
 * (docs/STAGE_330_DESIGN.md, Evidence; `src/images/AGENTS.md`): drives an already running server
 * over HTTP as the development personas (`fixtures/ravenford/personas.json`, so the server runs
 * with AUTH_MODE=dev-personas). The DM authors Tomas Reed (or finds him), his canonical portrait is
 * generated by the server's own worker and generator, the DM approves it, and the player sees it
 * only then. The image ledger is read from `DATABASE_URL` (the server's database; the development
 * database by default). The smoke reads no key and no env file, and never causes a paid text call:
 * see `image-smoke/author.ts`. With `openrouter-openai` it causes exactly one paid image call,
 * within the stored ceiling: run it only with the owner's authorization for that call.
 */
const write = (line: string) => {
  process.stdout.write(`${line}\n`);
};

async function personaTokens(): Promise<{ dm: string; player: string }> {
  const file = JSON.parse(await readFile(DEFAULT_PERSONAS_FILE, 'utf8')) as {
    personas: { token: string; actorId: string }[];
  };
  const token = (actorId: string) => {
    const persona = file.personas.find((candidate) => candidate.actorId === actorId);
    if (!persona) throw new SmokeUsageError(`no development persona ${actorId}`);
    return persona.token;
  };
  return { dm: token('dm-ravenford'), player: token('player-elowen') };
}

async function main(): Promise<number> {
  let options: SmokeOptions;
  try {
    options = parseSmokeArgs(process.argv.slice(2));
  } catch (error) {
    if (!(error instanceof SmokeUsageError)) throw error;
    process.stderr.write(`images:smoke: ${error.message}\n${SMOKE_USAGE}\n`);
    return EXIT.refused;
  }
  // The server's own rule: the development database unless DATABASE_URL names another.
  const fromEnvironment = process.env['DATABASE_URL'];
  const databaseUrl =
    fromEnvironment === undefined || fromEnvironment === '' ? DEV_DATABASE_URL : fromEnvironment;
  write(
    `images:smoke: ${options.generator} via ${options.server.origin}; ledger and storage read from ` +
      describeDatabaseUrl(databaseUrl),
  );
  const store = postgresSmokeStore(databaseUrl);
  try {
    return await runImageSmoke({
      options,
      client: new SmokeClient(options.server, await personaTokens(), globalThis.fetch),
      store,
      log: write,
      sleep: (ms) => delay(ms),
      now: () => performance.now(),
      runId: `image-smoke.${randomUUID().slice(0, 8)}`,
    });
  } finally {
    await store.close();
  }
}

main().then(
  (code) => {
    process.exitCode = code;
  },
  (error: unknown) => {
    process.stderr.write(`images:smoke: ${error instanceof Error ? error.message : 'error'}\n`);
    process.exitCode = EXIT.failed;
  },
);
