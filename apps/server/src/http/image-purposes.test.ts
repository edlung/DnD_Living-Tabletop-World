import {
  ImageGenerationError,
  createPlaceholderImageGenerator,
  type ImageGenerator,
} from '@ltw/ai';
import type {
  AssetLineageResponse,
  CommandResult,
  EntityAssetsResponse,
  EntityPresentationResponse,
} from '@ltw/contracts';
import type { WorldEngine } from '@ltw/domain';
import type { FastifyInstance } from 'fastify';
import { beforeEach, describe, expect, it } from 'vitest';

import { InMemoryAssetContentStore } from '../assets/content-store.ts';
import { AssetWorker } from '../assets/worker.ts';
import { createLogger } from '../platform/logging/logger.ts';
import {
  TOKENS,
  get,
  post,
  ravenfordApp,
  seededEngine,
  testAiGateway,
  testAuthoring,
} from '../testing/ravenford-app.ts';

/**
 * Figures and battle maps over HTTP (docs/adr/0035-images.md §4): requested by the DM through the
 * command route, generated by the worker, shown to players only once approved, in their entity
 * assets and their presentation, with the content route serving their bytes; and a generation
 * that made no call (`UNAVAILABLE`) leaves the neutral fallback.
 */
const BASE = '/campaigns/ravenford';
const ELOWEN = 'elowen-starwhisper';
const ROAD = 'old-trade-road';

let engine: WorldEngine;
let contents: InMemoryAssetContentStore;
let app: FastifyInstance;
let counter = 0;

beforeEach(async () => {
  engine = await seededEngine();
  contents = new InMemoryAssetContentStore();
  app = await ravenfordApp(engine, testAiGateway(), testAuthoring(), contents);
});

const command = async (token: string, body: Record<string, unknown>) => {
  counter += 1;
  return (
    await post(
      app,
      `${BASE}/commands`,
      { commandId: `purpose.${String(counter)}`, command: body },
      token,
    )
  ).json<CommandResult>();
};

const runWorker = (generator: ImageGenerator = createPlaceholderImageGenerator()) =>
  new AssetWorker({
    engine,
    contents,
    generator,
    timeoutMs: 1_000,
    logger: createLogger({ service: 'purpose-test', level: 'silent' }),
  }).runOnce('ravenford');

async function generated(entityId: string, extra: Record<string, unknown>): Promise<string> {
  const requested = await command(TOKENS.dm, { type: 'RequestAsset', entityId, ...extra });
  if (requested.status !== 'accepted') throw new Error(`request ${JSON.stringify(requested)}`);
  await runWorker();
  return `${requested.commandId}#0~asset`;
}

async function approved(
  entityId: string,
  extra: Record<string, unknown> = { variant: 'reference' },
) {
  const assetId = await generated(entityId, extra);
  const result = await command(TOKENS.dm, { type: 'ApproveAsset', assetId });
  if (result.status !== 'accepted') throw new Error('approval rejected');
  return assetId;
}

const presentation = async (
  entityId: string,
  token: string = TOKENS.player,
  perspective = 'PLAYER',
) =>
  (
    await get(app, `${BASE}/entities/${entityId}/presentation?perspective=${perspective}`, token)
  ).json<EntityPresentationResponse>().presentation;

const playerAssets = async (entityId: string) =>
  (
    await get(app, `${BASE}/entities/${entityId}/assets?perspective=PLAYER`, TOKENS.player)
  ).json<EntityAssetsResponse>().assets;

const FIGURE = { variant: 'derived', label: 'figure', purpose: 'figure' } as const;

/** Real images, seeds and imports: generous under a loaded machine (the unit default is 5 s). */
const SLOW_MS = 30_000;

describe('a figure and a battle map over HTTP', { timeout: SLOW_MS }, () => {
  it('reach a player only once the DM approves them', async () => {
    await approved(ELOWEN);
    const figure = await generated(ELOWEN, FIGURE);
    expect((await playerAssets(ELOWEN)).map((asset) => asset.purpose)).toEqual(['image']);
    expect((await presentation(ELOWEN)).figure).toBeNull();
    expect((await presentation(ELOWEN, TOKENS.dm, 'DM')).figure).toBeNull();

    expect((await command(TOKENS.dm, { type: 'ApproveAsset', assetId: figure })).status).toBe(
      'accepted',
    );
    const assets = await playerAssets(ELOWEN);
    expect(assets.map((asset) => [asset.variant, asset.purpose])).toEqual([
      ['reference', 'image'],
      ['derived', 'figure'],
    ]);
    const shown = (await presentation(ELOWEN)).figure;
    expect(shown).toMatchObject({ variant: 'derived', purpose: 'figure' });
    const bytes = await get(
      app,
      `${BASE}/assets/content/${shown?.contentHash ?? ''}?perspective=PLAYER`,
      TOKENS.player,
    );
    expect(bytes.statusCode).toBe(200);
    expect(bytes.headers['content-security-policy']).toBe(
      "default-src 'none'; style-src 'unsafe-inline'; sandbox",
    );

    await approved(ROAD);
    await approved(ROAD, { variant: 'derived', label: 'map', purpose: 'battle-map' });
    expect(await presentation(ROAD)).toMatchObject({
      image: { purpose: 'image', variant: 'reference' },
      figure: null,
      battleMap: { purpose: 'battle-map', variant: 'derived' },
    });
    const lineage = (await get(app, `${BASE}/assets`, TOKENS.dm)).json<AssetLineageResponse>();
    expect(lineage.assets.map((asset) => asset.purpose)).toEqual([
      'image',
      'figure',
      'image',
      'battle-map',
    ]);
  });

  it('are the DM’s to request, and only for the kinds that have them', async () => {
    await approved(ELOWEN);
    await approved(ROAD);
    expect(
      await command(TOKENS.player, { type: 'RequestAsset', entityId: ELOWEN, ...FIGURE }),
    ).toMatchObject({ error: { code: 'FORBIDDEN' } });
    expect(
      await command(TOKENS.dm, { type: 'RequestAsset', entityId: ROAD, ...FIGURE }),
    ).toMatchObject({
      status: 'rejected',
      code: 'INVALID_ASSET',
    });
    expect(
      await command(TOKENS.dm, {
        type: 'RequestAsset',
        entityId: ELOWEN,
        variant: 'reference',
        purpose: 'battle-map',
      }),
    ).toMatchObject({ status: 'rejected', code: 'INVALID_ASSET' });
  });
});

describe('a generation that made no call', { timeout: SLOW_MS }, () => {
  it('fails as UNAVAILABLE for the DM and leaves the players’ fallback', async () => {
    const requested = await command(TOKENS.dm, {
      type: 'RequestAsset',
      entityId: ELOWEN,
      variant: 'reference',
    });
    const denied: ImageGenerator = {
      id: 'openrouter-openai',
      generate: () =>
        Promise.reject(new ImageGenerationError('UNAVAILABLE', 'no image budget for this call')),
    };
    expect(await runWorker(denied)).toEqual({ started: 1, completed: 0, failed: 1 });
    const lineage = (await get(app, `${BASE}/assets`, TOKENS.dm)).json<AssetLineageResponse>();
    expect(lineage.requests).toEqual([
      expect.objectContaining({
        requestId: `${requested.status === 'accepted' ? requested.commandId : ''}#0`,
        purpose: 'image',
        status: 'FAILED',
        failure: 'UNAVAILABLE',
      }),
    ]);
    expect(lineage.assets).toEqual([]);
    expect((await presentation(ELOWEN)).image).toBeNull();
    expect(await playerAssets(ELOWEN)).toEqual([]);
  });
});
